LDRAW_COLOR_BY_CODE: Dict[int, LDrawColorRecord] = {
    r.code: r for r in LDRAW_FULL_PALETTE_RECORDS
}

# Legacy Rebrickable internal color ID crosswalk where Rebrickable ID != LDraw CODE:
REBRICKABLE_TO_LDRAW_COLOR_ALIASES: Dict[int, int] = {
    158: 326,  # Rebrickable Yellowish Green -> LDraw 326 Yellowish_Green
    182: 57,   # Rebrickable Trans-Orange -> LDraw 57 Trans_Orange
}


def resolve_ldraw_color_record(color_id: int) -> Optional[LDrawColorRecord]:
    cid = int(color_id)
    if cid in LDRAW_COLOR_BY_CODE:
        return LDRAW_COLOR_BY_CODE[cid]
    mapped = REBRICKABLE_TO_LDRAW_COLOR_ALIASES.get(cid)
    return LDRAW_COLOR_BY_CODE.get(mapped) if mapped is not None else None


def get_ldraw_color_finish(color_id: int) -> str:
    rec = resolve_ldraw_color_record(color_id)
    return rec.finish if rec is not None else "SOLID"
